/** Wrap the app. Dynamic (wallpaper) colour is off: Substratal themes are the product palette. */
@Composable
fun SubstratalTheme(mode: ThemeMode, light: LightTheme, dark: DarkTheme, content: @Composable () -> Unit) {
    val isDark = when (mode) { ThemeMode.LIGHT -> false; ThemeMode.DARK -> true; ThemeMode.SYSTEM -> isSystemInDarkTheme() }
    MaterialTheme(colorScheme = if (isDark) dark.scheme else light.scheme, content = content)
}
